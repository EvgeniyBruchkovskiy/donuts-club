/** Pass Type ID certificate + its private key (PEM, secrets APPLE_PASS_CERT / APPLE_PASS_KEY). */
export interface AppleSigner {
  certPem: string;
  keyPem: string;
  /** Apple WWDR G4 intermediate — public, shipped in assets/wallet. */
  wwdrPem: string;
}

const ASSETS = new URL("../../assets/wallet/", import.meta.url);

export const wwdrPem = () => readFileSync(new URL("AppleWWDRCAG4.crt", ASSETS), "utf8");

/** icon / logo PNGs (1x, @2x, @3x) generated by scripts/gen-wallet-assets.mjs. */
export function passImages(): Record<string, Uint8Array> {
  const out: Record<string, Uint8Array> = {};
  for (const f of readdirSync(ASSETS)) if (f.endsWith(".png")) out[f] = readFileSync(new URL(f, ASSETS));
  return out;
}

